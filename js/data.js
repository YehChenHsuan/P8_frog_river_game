const VOCAB_MAP = new Map(P8_VOCABULARY.map(v => [v.id, v]));

class QuestionGenerator {
  static shuffle(arr) {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  }

  static generateListenQuestion() {
    const target = P8_VOCABULARY[Math.floor(Math.random() * P8_VOCABULARY.length)];
    const others = P8_VOCABULARY.filter(v => v.id !== target.id);
    const shuffledOthers = this.shuffle(others);
    const options = this.shuffle([target, shuffledOthers[0], shuffledOthers[1]]);

    return {
      type: "LISTEN_HOP",
      target: target,
      promptText: target.word,
      promptSub: target.zh,
      ttsAudioId: target.id,
      options: options,
      correctId: target.id
    };
  }

  static generatePhonicsQuestion() {
    const letters = Object.keys(PHONICS_GROUPS);
    const targetLetter = letters[Math.floor(Math.random() * letters.length)];
    const targetWordIds = PHONICS_GROUPS[targetLetter];
    
    // 從該字母挑選一個作為目標
    const validTargets = targetWordIds.map(id => VOCAB_MAP.get(id)).filter(Boolean);
    const target = validTargets.length > 0 ? validTargets[Math.floor(Math.random() * validTargets.length)] : P8_VOCABULARY[0];
    
    // 干擾項
    const distractors = P8_VOCABULARY.filter(v => !targetWordIds.includes(v.id));
    const shuffledDis = this.shuffle(distractors);
    const options = this.shuffle([target, shuffledDis[0], shuffledDis[1]]);

    return {
      type: "BEGINNING_SOUNDS",
      target: target,
      targetLetter: targetLetter,
      promptText: `Letter [ ${targetLetter} ]`,
      promptSub: `Find the word starting with ${targetLetter}`,
      ttsAudioId: target.id,
      ttsText: `Letter ${targetLetter}. Sound ${targetLetter[0].toLowerCase()}. Find the word that starts with ${targetLetter}.`,
      options: options,
      correctId: target.id
    };
  }

  static generateActionQuestion() {
    const qData = ANIMAL_ACTION_QUESTIONS[Math.floor(Math.random() * ANIMAL_ACTION_QUESTIONS.length)];
    const target = VOCAB_MAP.get(qData.correct) || {
      id: qData.correct,
      word: qData.correct,
      zh: qData.correct,
      image: `P8_flashcards_images/P8_${qData.correct}.webp`,
      audioEn: `P8_flashcards_audios/P8_${qData.correct}.mp3`,
      audioZh: `P8_flashcards_audios/P8_${qData.correct}_zh.mp3`
    };

    const optionItems = qData.options.map(id => VOCAB_MAP.get(id) || {
      id: id,
      word: id,
      zh: id,
      image: `P8_flashcards_images/P8_${id}.webp`,
      audioEn: `P8_flashcards_audios/P8_${id}.mp3`,
      audioZh: `P8_flashcards_audios/P8_${id}_zh.mp3`
    });

    return {
      type: "ANIMAL_ACTIONS",
      target: target,
      promptText: qData.question,
      promptSub: `${qData.sentence.replace(target.word, "___")}`,
      ttsAudioId: target.id,
      ttsText: `${qData.question} ${qData.sentence}`,
      options: this.shuffle(optionItems),
      correctId: target.id,
      fullSentence: qData.sentence
    };
  }

  static generateEndlessQuestion(stepIndex = 1) {
    const modes = ["LISTEN_HOP", "BEGINNING_SOUNDS", "ANIMAL_ACTIONS"];
    const mode = modes[(stepIndex - 1) % modes.length];
    if (mode === "LISTEN_HOP") return this.generateListenQuestion();
    if (mode === "BEGINNING_SOUNDS") return this.generatePhonicsQuestion();
    return this.generateActionQuestion();
  }
}

